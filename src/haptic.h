#pragma once

// Вибромоторчик: отклик на нажатия, чтобы чувствовать, что плата тебя поняла.
typedef enum {
    HAP_FIRE,          // кнопка распознана и ушла в стек: один короткий (ждёт конца бзыньков End)
    HAP_END1,          // End распознан, будет ряд 1 — один бзыньк
    HAP_END2,          // End распознан, будет ряд 2 — два бзынька
    HAP_END_SVC,       // End распознан в режиме настроек — три бзынька
    HAP_SVC1,          // End держат 2 с (первое долгое) — один длинный
    HAP_SVC2,          // второе долгое — два длинных, настройки взведены
    HAP_FAIL,          // кнопка не ушла в сеть — три коротких
    HAP_CHORD,         // сервисный аккорд принят (сброс сети / OTA) — очень длинный
} haptic_t;

void haptic_init(void);
void haptic_play(haptic_t p);
