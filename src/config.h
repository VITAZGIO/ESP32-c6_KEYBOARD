#pragma once

// --------------------------- ПИНЫ ---------------------------

#define PIN_END       6     // End, провод с ножки самой кнопки — линия ЧТЕНИЯ (10 кОм)
#define PIN_END_SCAN  7     // End, провод с диода — линия СКАНА (10 кОм)
#define PIN_SCAN      4     // общая линия цифр (с диодов) — СКАН (10 кОм)
#define PIN_BAT_ADC   1     // делитель 20k/20k с аккумулятора

// Вибромоторчик (3 В, 85 мА) через NPN-транзистор: GPIO3 -> 1к -> база,
// эмиттер на GND, мотор между 3V3 и коллектором, диод 1N4148 поперёк мотора
// (катод к 3V3), 100к база-GND. Пин не занят матрицей — проверь, что он выведен на плате.
#define HAPTIC_ENABLED       1
#define PIN_HAPTIC           3
#define HAPTIC_ACTIVE_LEVEL  1     // 1 — транзистор открывается высоким уровнем
#define HAPTIC_FIRE_MS       45    // длина вибрации «кнопка принята»

#define N_DIGITS 6
#define DIGIT_PINS_INIT {19, 2, 5, 20, 18, 14}    // цифры 1..6 (линии чтения)
                                                  // ESP32-C6 SuperMini: все на краях платы

// -------------------------- END ----------------------------

// End в матрице клавиатуры. В простое клава не сканирует, и нажатие любой
// клавиши ряда End тянет линию чтения в ноль — по этому плата просыпается.
// Дальше клава сканирует, и End = линия чтения в нуле в момент скана
// столбца End (как цифры).
#define END_POLL_MS        2     // шаг логики, пока плата бодрствует
#define END_PRESS_SCANS    2     // 2 скана подряд в нуле = End нажат
#define END_RELEASE_SCANS  2     // 2 скана подряд в единице = End отпущен
#define END_PRESS_SAMPLES  1
#define WAKE_GRACE_MS      400   // после пробуждения не спать столько, даже если
                                 // клава ещё не начала сканировать
#define END_RELEASE_MS     25    // столько End должен быть отпущен, чтобы
                                 // считаться отпущенным (дребезг свича ~10 мс)

// Опрос End. Пока клава сканирует, End приходит импульсами ~0.1 мс раз в 2 мс
// (замер анализатором 11.11.2026) — пробуждение по уровню их пропускает.
// Поэтому чип сам просыпается по таймеру и слушает сканы End POLL_LISTEN_MS.
#define PIN_KB_ALIVE       19    // линия цифры 1: импульсы всегда, пока клава сканирует
#define POLL_PERIOD_MS     20    // клава сканирует: проверять End так часто (~5-8 мА)
#define KB_CHECK_MS        1000  // клава молчит: так часто проверять, не проснулась ли
#define POLL_LISTEN_MS     6     // окно прослушки: 2-3 скана по 2 мс
#define POLL_END_PULSES    2     // столько импульсов End за окно = End зажат

// ------------------------- ЦИФРЫ ---------------------------
// Клава сканирует матрицу, только пока зажата какая-то её клавиша,
// примерно раз в 2 мс. Цифру решаем по последовательным сканам.

#define DIGIT_PRESS_SCANS    2   // 2 скана подряд в нуле = цифра нажата
#define DIGIT_RELEASE_SCANS  2   // 2 скана подряд в единице = отпущена
#define SCAN_SILENCE_MS      40  // сканы пропали на 40 мс = клава уснула,
                                 // все цифры считаем отпущенными
#define MAX_SIMULTANEOUS     2   // больше цифр разом — не кнопка, игнор

// ------------------------- РЕЖИМЫ --------------------------

#define TAP_MIN_MS         40    // короче — дребезг/призрак, не тап
#define TAP_MAX_MS         600   // тап End (без цифр) переключает ряд 1 <-> 2
#define ROW_TIMEOUT_MS     5000  // столько без тапов и кнопок — снова ряд 1
#define SERVICE_HOLD_MS    2000  // удержание End дольше = одно «долгое»
#define SERVICE_GAP_MS     1500  // второе долгое начать не позже, чем через столько после первого
#define SERVICE_WINDOW_MS  5000  // после двух долгих: столько ждём End + цифру настроек

// ------------------------ ОТПРАВКА -------------------------

#define PULSE_MS       300    // сколько кнопка держится в ON
#define ON_RETRIES     2      // повторные ON внутри импульса (первый пакет после сна
#define ON_RETRY_MS    100    // иногда теряется); повтор того же ON ничего не переключает
#define OFF_RETRIES    2      // повторные OFF (пакеты в эфире теряются)
#define OFF_RETRY_MS   900
#define REFIRE_MS      250    // минимум между срабатываниями одной кнопки

// ------------------------- БАТАРЕЯ -------------------------

#define BAT_MIN_MV     3300   // 0 %
#define BAT_MAX_MV     4200   // 100 %
#define BAT_REPORT_MS  (6UL * 60 * 60 * 1000)   // отчёт раз в 6 часов

// -------------------------- ZIGBEE -------------------------

#define ZB_MANUFACTURER  "VITAZGIO"
#define ZB_MODEL         "AulaKeys"
#define EP_BASE_FIRST    10   // 10..15 — End + цифра
#define EP_ALT_FIRST     20   // 20..25 — тап End, потом End + цифра
#define ZB_KEEP_ALIVE_MS 4000 // раз во сколько плата спрашивает роутер

// -------------------------- ТЕСТ ---------------------------
// 1 = Zigbee не запускается вообще: проверка, кто будит чип и сколько
//     ест плата без радио. Кнопки в сеть не уходят. Для работы — 0.
#define TEST_NO_ZIGBEE   0

